// Example of break statement
console.log("Break Example:");

for (let i = 1; i <= 10; i++) {
    if (i == 5) {
        break;
    }
    console.log(i);
}

// Example of continue statement
console.log("Continue Example:");

for (let i = 1; i <= 5; i++) {
    if (i == 3) {
        continue;
    }
    console.log(i);
}